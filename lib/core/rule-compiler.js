/**
 * 规则编译器
 *
 * 职责：把多个 Rule 合并为单个 markdown 字符串
 * - 按 category 分组排序
 * - 为每条规则生成 ### 小节
 * - 顶部加注释头
 *
 * 设计原则：纯函数，输入 Rule[]，输出 markdown 字符串
 */

/**
 * 编译规则为 markdown
 * @param {Array} rules Rule 对象数组（来自 rule-store.list）
 * @param {Object} [options]
 * @param {string} [options.toolName] 目标工具名（用于注释头）
 * @param {string} [options.toolDisplayName] 目标工具显示名
 * @returns {string}
 */
function compile(rules, options = {}) {
  const { toolName = 'all', toolDisplayName = 'all' } = options;
  const enabled = rules.filter((r) => r.frontmatter.enabled);
  const header = `<!--
  Generated by aicode v0.1.0
  Target: ${toolDisplayName} (${toolName})
  Generated at: ${new Date().toISOString()}
  Source rules: ${enabled.length}
-->

# 项目开发规范

> 此文件由 aicode 自动生成，请勿手动修改。
> 修改规则请使用 \`aicode rule add/edit\`，然后执行 \`aicode sync\`。

`;

  if (enabled.length === 0) {
    return header + '\n_（暂无启用的规则，请通过 `aicode rule add` 添加）_\n';
  }

  // 按 category 排序，category 不在预设列表的放最后
  const order = ['backend', 'frontend', 'general', 'custom'];
  enabled.sort((a, b) => {
    const ai = order.indexOf(a.frontmatter.category);
    const bi = order.indexOf(b.frontmatter.category);
    return (ai === -1 ? 999 : ai) - (bi === -1 ? 999 : bi);
  });

  const sections = enabled.map((r) => formatSection(r));
  return header + '\n' + sections.join('\n---\n\n') + '\n';
}

/**
 * 单条规则 → markdown 小节
 * @param {Object} rule
 * @returns {string}
 */
function formatSection(rule) {
  const { name, frontmatter, body } = rule;
  const description = frontmatter?.description || '';
  const descLine = description ? `> ${description}\n\n` : '';
  return `### ${name}\n\n${descLine}${body || '_（规则内容为空）_'}`;
}

module.exports = { compile };
